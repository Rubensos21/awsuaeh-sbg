export const awsServices: readonly AwsService[] = (
  Object.entries(catalog) as [CatalogCategory, ServiceSeed[]][]
).flatMap(([category, entries]) => entries.map(([name, description, popularityScore, documentationPath, iconName]) => {
  const { label, badgeBg, badgeText } = serviceCategoryDetails[category];
  return {
    id: name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/g, ''),
    name,
    category,
    categoryLabel: label,
    description,
    popularityScore,
    icon: iconName === 'robotics' ? 'robotics' : `/icons/services/${iconName}.svg`,
    colorScheme: { badgeBg, badgeText, iconBorder: '#3a424c' },
    link: `https://docs.aws.amazon.com/${documentationPath}`,
  };
}));
